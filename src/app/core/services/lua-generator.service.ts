import { Injectable, inject } from '@angular/core';
import { FormspecAST } from '../models/formspec.models';
import { FormspecParserService } from './formspec-parser.service';

@Injectable({
  providedIn: 'root',
})
export class LuaGeneratorService {
  private readonly parser: FormspecParserService;

  constructor(parser?: FormspecParserService) {
    this.parser = parser ?? inject(FormspecParserService);
  }

  /**
   * Generates a complete, production-ready responsive Luanti Lua mod file.
   */
  generateResponsiveMod(formName: string, ast: FormspecAST): string {
    const sanitizedName = formName.toLowerCase().replace(/[^a-z0-9_]/g, '_') || 'custom_gui';
    const formspecStr = this.parser.serialize(ast);

    // Extract all button/field names for callback scaffolding
    const interactiveNames = this.extractInteractiveNames(ast);
    const callbackBranches = interactiveNames
      .map((name) => `        if fields.${name} then\n            -- Handle ${name} interaction\n            core.chat_send_player(player_name, "Clicked ${name}")\n        end`)
      .join('\n');

    return `-- ==========================================================
-- Generated by Luanti Formspec Studio (Formspec v7 Pipeline)
-- Mod: ${sanitizedName}
-- ==========================================================

local MODNAME = "${sanitizedName}"

--- Returns adaptive formspec markup dynamically based on player window telemetry
-- @param player_name string
-- @return string
local function get_${sanitizedName}_formspec(player_name)
    local player = core.get_player_by_name(player_name)
    if not player then return "" end

    -- 1. Fetch real-time client window and screen metrics
    local info = core.get_player_window_information(player_name) or {}
    local max_size = info.max_formspec_size or { x = 16, y = 10 }
    local is_touch = info.touch_controls or false

    -- 2. Responsive Breakpoint Decision (Mobile/Touch vs Desktop/Wide)
    if max_size.x < 14 or is_touch then
        -- Compact Mobile / Touch Breakpoint (Tabbed fallback)
        local w = math.min(max_size.x, 10)
        local h = math.min(max_size.y, 11)
        return table.concat({
            "formspec_version[7]",
            "size[", w, ",", h, "]",
            "padding[0.1,0.1]",
            "label[0.5,0.4;${sanitizedName} (Mobile View)]",
            "button[0.5,", h - 1.2, ";", w - 1, ",0.9;btn_action;Submit]"
        }, "")
    else
        -- Standard / Widescreen Desktop Breakpoint
        return "${formspecStr}"
    end
end

-- ==========================================================
-- Event Handling Callback
-- ==========================================================
core.register_on_player_receive_fields(function(player, formname, fields)
    if formname == MODNAME .. ":main" then
        local player_name = player:get_player_name()

${callbackBranches || '        -- No named buttons registered\n        if fields.quit then\n            return\n        end'}
    end
end)

-- ==========================================================
-- Test Chatcommand: /open_${sanitizedName}
-- ==========================================================
core.register_chatcommand("open_" .. MODNAME, {
    description = "Open the ${sanitizedName} GUI dialog",
    privs = { interact = true },
    func = function(name, param)
        local form = get_${sanitizedName}_formspec(name)
        core.show_formspec(name, MODNAME .. ":main", form)
        return true, "Opened " .. MODNAME
    end,
})
`;
  }

  private extractInteractiveNames(ast: FormspecAST): string[] {
    const names: string[] = [];
    for (const node of ast.children) {
      if (node.name && (node.type.startsWith('button') || node.type === 'field' || node.type === 'checkbox')) {
        names.push(node.name);
      }
      if (node.children) {
        for (const child of node.children) {
          if (child.name) names.push(child.name);
        }
      }
    }
    return Array.from(new Set(names));
  }
}
